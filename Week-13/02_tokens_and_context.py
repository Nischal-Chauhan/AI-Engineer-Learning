# 2. Understanding context window
print("\n2. What is a context window?")
print("A context window is the amount of information")
print("an LLM can process during an interaction.")

# 3. What goes into a context window?
print("\n3. Context window can include:")
print("- Current user question")
print("- Previous conversation")
print("- Instructions")
print("- Information provided to the model")

# 4. Important point
print("\n4. Important points:")
print("- One token does not always equal one word.")
print("- Different models have different context limits.")
print("- Longer conversations use more tokens.")

